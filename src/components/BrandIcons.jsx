export function InstituteBadge({ issuer, size = 'md' }) {
  const lower = issuer.toLowerCase();
  const boxClass =
    size === 'sm'
      ? 'h-8 w-8 rounded-lg p-1'
      : 'h-11 w-11 rounded-xl p-1.5';

  let mark = <CourseraLogoMark className="h-full w-full" />;
  if (lower.includes('ibm')) {
    mark = <IbmLogoMark className="h-full w-full" />;
  } else if (lower.includes('deeplearning')) {
    mark = <DeepLearningLogoMark className="h-full w-full" />;
  } else if (lower.includes('google')) {
    mark = <GoogleCloudLogoMark className="h-full w-full" />;
  }

  return (
    <span
      title={issuer}
      className={`inline-flex shrink-0 items-center justify-center bg-white shadow-[0_4px_12px_rgba(0,0,0,0.3)] ring-1 ring-black/10 ${boxClass}`}
    >
      {mark}
    </span>
  );
}
